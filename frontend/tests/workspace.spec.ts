import { test, expect } from '@playwright/test'
import fs from 'node:fs'

const reference = fs.readFileSync('../problems/broken-code-formatter/author/reference.py', 'utf8')
const draftKey = 'code-relay:draft:broken-code-formatter:v1:python'

async function draft(page: import('@playwright/test').Page, source: string) {
  await page.evaluate(({key, source}) => localStorage.setItem(key, source), {key: draftKey, source})
  await page.reload()
  await expect(page.getByRole('button', {name: 'Submit ↗', exact: true})).toBeEnabled()
  await expect(page.getByTestId('code-editor').locator('.monaco-editor')).toBeVisible()
}

test('home, catalog, workspace, samples, submission, review, persisted trajectory, and drafts', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', {name: /Think it through/})).toBeVisible()
  await page.screenshot({path: '../.runtime/qa-home.png', fullPage: true})
  await page.getByRole('link', {name: /Start practicing/}).click()
  await expect(page).toHaveURL(/\/problems$/)
  await page.getByRole('link', {name: /The Broken Code Formatter/}).click()
  await expect(page).toHaveURL(/\/problems\/broken-code-formatter$/)
  await expect(page.getByRole('heading', {name: 'The Broken Code Formatter', level: 1}).first()).toBeVisible()
  await draft(page, reference)
  await page.getByRole('button', {name: '▷ Run samples', exact: true}).click()
  await expect(page.getByLabel('Judge results').getByText('Accepted', {exact: true}).first()).toBeVisible()
  await expect(page.getByText('6 passed · 6 attempted / 6 total', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'Submit ↗', exact: true}).click()
  await expect(page.getByText('65 passed · 65 attempted / 65 total', {exact: true})).toBeVisible({timeout: 30_000})
  await expect(page.getByText('Human review required; missing reviews are not zero.')).toBeVisible()
  await page.screenshot({path: '../.runtime/qa-workspace.png', fullPage: true})
  await page.getByRole('button', {name: /Review this attempt’s code quality/}).click()
  await expect(page.getByRole('heading', {name: 'Human code review'})).toBeVisible()
  for (const select of await page.locator('.review-form fieldset:not(.complexity-form) select').all()) await select.selectOption('4')
  await page.getByLabel('Analysis status', {exact: true}).selectOption('assessed')
  await page.getByLabel('Worst-case time', {exact: true}).fill('O(L)')
  await page.getByLabel('Auxiliary space', {exact: true}).fill('O(L)')
  await page.getByLabel('Space including stored input/output', {exact: true}).fill('O(L)')
  await page.getByLabel('Complexity reasoning', {exact: true}).fill('Each character is visited once; the stack and stored source grow with L.')
  await page.getByLabel('Review rationale', {exact: true}).fill('Clear state transitions, descriptive names, and a linear parser.')
  await page.getByRole('button', {name: 'Save review', exact: true}).click()
  await expect(page.getByText('Review saved to this source snapshot.')).toBeVisible()
  await expect(page.locator('.attempt-detail .final-score strong')).toHaveText('100%')
  await expect(page.getByLabel('Reviewed complexity', {exact: true})).toContainText('Each character is visited once')
  await page.reload()
  await page.getByRole('tab', {name: /History & review/}).click()
  await expect(page.locator('.attempt-list button').first()).toContainText('100% overall')
  await page.locator('.attempt-list button').first().click()
  await expect(page.getByLabel('Review rationale', {exact: true})).toHaveValue('Clear state transitions, descriptive names, and a linear parser.')
  await expect(page.getByLabel('Analysis status', {exact: true})).toHaveValue('assessed')
  await expect(page.getByLabel('Worst-case time', {exact: true})).toHaveValue('O(L)')
  await expect(page.locator('.source-snapshot')).toHaveText(reference)
  await page.getByRole('button', {name: 'Reset starter', exact: true}).click({noWaitAfter: true})
  // A dismissal is the default for unhandled confirm dialogs; the draft must survive.
  expect(await page.evaluate(key => localStorage.getItem(key), draftKey)).toBe(reference)
  await draft(page, "print('INVALID')\n")
  await page.getByRole('button', {name: 'Submit ↗', exact: true}).click()
  await expect(page.getByLabel('Judge results').getByText('Wrong Answer', {exact: true}).first()).toBeVisible({timeout: 30_000})
  await page.getByRole('tab', {name: /History & review/}).click()
  await expect(page.locator('.attempt-list button')).toHaveCount(2)
  await expect(page.getByLabel('Progress across attempts')).toContainText('2 complete assessments')
  await page.screenshot({path: '../.runtime/qa-trajectory.png', fullPage: true})
  await page.locator('.attempt-list button').last().click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', {name: 'Restore to editor'}).click()
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), draftKey)).toBe(reference)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', {name: 'Reset starter', exact: true}).click()
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), draftKey)).not.toBe(reference)
  expect(errors).toEqual([])
})

test('custom input, language drafts, responsive layout, and unavailable backend', async ({page}) => {
  await page.goto('/problems/broken-code-formatter')
  await draft(page, 'import sys\nsys.stdout.write(sys.stdin.read())\n')
  await page.getByTestId('code-editor').click({position: {x: 180, y: 50}})
  await page.keyboard.press('Control+End')
  await page.keyboard.type('# browser edit')
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), draftKey)).toContain('# browser edit')
  await draft(page, 'import sys\nsys.stdout.write(sys.stdin.read())\n')
  await page.getByLabel('Custom input', {exact: true}).check()
  await page.getByLabel('Standard input', {exact: true}).fill('my custom input')
  await page.getByRole('button', {name: '▷ Run input', exact: true}).click()
  await expect(page.getByLabel('Judge results').getByText('Completed', {exact: true}).first()).toBeVisible()
  await expect(page.getByText('Custom input has no expected output, correctness verdict, or assessment score.')).toBeVisible()
  const language = page.getByLabel('LANGUAGE', {exact: true})
  const jsAvailable = await language.locator('option[value="javascript"]').isEnabled()
  if (jsAvailable) {
    await language.selectOption('javascript')
    await page.evaluate(() => localStorage.setItem('code-relay:draft:broken-code-formatter:v1:javascript', '// JS draft'))
    await page.reload()
    await expect(language).toHaveValue('javascript')
    await language.selectOption('python')
    expect(await page.evaluate(key => localStorage.getItem(key), draftKey)).toBe('import sys\nsys.stdout.write(sys.stdin.read())\n')
  }
  await page.setViewportSize({width: 390, height: 844})
  await expect(page.getByRole('button', {name: 'Submit ↗', exact: true})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.screenshot({path: '../.runtime/qa-mobile.png', fullPage: true})
  await page.route('**/api/**', route => route.abort())
  await page.goto('/problems')
  await expect(page.getByRole('alert')).toContainText('Cannot reach the local judge')
  await page.unroute('**/api/**')
  await page.getByRole('button', {name: 'Retry', exact: true}).click()
  await expect(page.getByRole('link', {name: /The Broken Code Formatter/})).toBeVisible()
})
